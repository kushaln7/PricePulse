"use client";

import React, { useState, useEffect } from "react";
import { 
  Play, 
  RotateCw, 
  ArrowUpRight, 
  ArrowDownRight, 
  Calendar, 
  Cpu, 
  AlertCircle, 
  CheckCircle2, 
  ShieldAlert, 
  Sparkles,
  Clock,
  History,
  Trash2,
  Info
} from "lucide-react";
import { PredictionResponse } from "@/types/api";
import { fetchPrediction } from "@/lib/api";

interface DashboardProps {
  initialPrediction: PredictionResponse | null;
  onPredictionUpdated?: (pred: PredictionResponse) => void;
}

interface HistoricalPredictionEntry {
  id: string;
  predictionTimestamp: string;
  targetTradingDate: string;
  asOfDate: string;
  currentPrice: number;
  predictedNextPrice: number;
  predictedReturnPercent: number;
  direction: "UP" | "DOWN";
  modelVersion: string;
  status: "Pending Session Close" | "Completed";
}

export const LivePredictionDashboard: React.FC<DashboardProps> = ({
  initialPrediction,
  onPredictionUpdated
}) => {
  const [prediction, setPrediction] = useState<PredictionResponse | null>(initialPrediction);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [lastUpdated, setLastUpdated] = useState<string | null>(null);
  const [historyLog, setHistoryLog] = useState<HistoricalPredictionEntry[]>([]);

  // Load prediction history from localStorage
  useEffect(() => {
    try {
      const stored = localStorage.getItem("pricepulse_prediction_history");
      if (stored) {
        setHistoryLog(JSON.parse(stored));
      }
    } catch {
      // localStorage may fail in private mode
    }
  }, []);

  const saveToHistory = (pred: PredictionResponse) => {
    try {
      const newEntry: HistoricalPredictionEntry = {
        id: `${pred.prediction_timestamp || Date.now()}`,
        predictionTimestamp: pred.prediction_timestamp || new Date().toISOString(),
        targetTradingDate: pred.target_date || "Next Session",
        asOfDate: pred.as_of_date,
        currentPrice: pred.current_price,
        predictedNextPrice: pred.predicted_next_price,
        predictedReturnPercent: pred.predicted_return_percent,
        direction: pred.direction,
        modelVersion: "XGBoost Regressor (25 Features)",
        status: "Pending Session Close"
      };

      setHistoryLog((prev) => {
        // Prevent duplicate immediate inserts
        const exists = prev.some((p) => p.predictionTimestamp === newEntry.predictionTimestamp);
        if (exists) return prev;
        const updated = [newEntry, ...prev.slice(0, 19)]; // Keep latest 20
        localStorage.setItem("pricepulse_prediction_history", JSON.stringify(updated));
        return updated;
      });
    } catch {
      // localStorage error fallback
    }
  };

  const clearHistory = () => {
    localStorage.removeItem("pricepulse_prediction_history");
    setHistoryLog([]);
  };

  useEffect(() => {
    if (initialPrediction) {
      setPrediction(initialPrediction);
      setLastUpdated(new Date().toLocaleTimeString());
      saveToHistory(initialPrediction);
    }
  }, [initialPrediction]);

  const handleRunPrediction = async (force: boolean = true) => {
    setLoading(true);
    setError(null);
    try {
      const result = await fetchPrediction(force);
      setPrediction(result);
      setLastUpdated(new Date().toLocaleTimeString());
      saveToHistory(result);
      if (onPredictionUpdated) {
        onPredictionUpdated(result);
      }
    } catch (err: unknown) {
      console.error("Prediction error:", err);
      setError(err instanceof Error ? err.message : "Market data temporarily unavailable. Please retry.");
    } finally {
      setLoading(false);
    }
  };

  const isUp = prediction?.direction === "UP";

  return (
    <section id="prediction-dashboard" className="py-24 px-4 sm:px-6 lg:px-8 max-w-7xl mx-auto">
      {/* Section Header */}
      <div className="flex flex-col md:flex-row md:items-end justify-between mb-10 gap-4">
        <div>
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-emerald-500/10 border border-emerald-500/20 text-emerald-400 text-xs font-mono mb-3">
            <Cpu className="w-3.5 h-3.5" />
            <span>PRIMARY INFERENCE DASHBOARD</span>
          </div>
          <h2 className="text-3xl sm:text-5xl font-extrabold text-white tracking-tight">
            Prediction Dashboard
          </h2>
          <p className="text-slate-400 text-sm sm:text-base mt-2 max-w-2xl font-light">
            Live machine learning estimates for the next trading session generated by the trained XGBoost model using fresh yfinance market feeds and 25 verified signals.
          </p>
        </div>

        {/* Action Button & Status Pill */}
        <div className="flex items-center gap-3">
          <div className="hidden sm:flex items-center gap-2 px-3.5 py-2 rounded-xl bg-slate-900 border border-slate-800 text-xs font-mono">
            <span className="w-2 h-2 rounded-full bg-emerald-400 animate-pulse" />
            <span className="text-slate-300">
              Model: <strong className="text-emerald-400">XGBoost v1.0</strong>
            </span>
          </div>

          <button
            onClick={() => handleRunPrediction(true)}
            disabled={loading}
            className={`flex items-center gap-2 px-6 py-3 rounded-xl font-bold text-xs tracking-wider uppercase transition-all shadow-xl cursor-pointer ${
              loading
                ? "bg-slate-800 text-slate-400 cursor-not-allowed border border-slate-700"
                : "bg-gradient-to-r from-emerald-500 to-teal-400 hover:from-emerald-400 hover:to-teal-300 text-slate-950 shadow-emerald-500/25 active:scale-95"
            }`}
          >
            {loading ? (
              <>
                <RotateCw className="w-4 h-4 animate-spin text-emerald-400" />
                <span>Running Inference...</span>
              </>
            ) : (
              <>
                <Play className="w-4 h-4 fill-slate-950" />
                <span>Run Prediction</span>
              </>
            )}
          </button>
        </div>
      </div>

      {/* Error Banner */}
      {error && (
        <div className="mb-8 p-4 rounded-2xl bg-rose-500/10 border border-rose-500/20 flex items-start gap-3 text-rose-300 text-sm">
          <AlertCircle className="w-5 h-5 text-rose-400 shrink-0 mt-0.5" />
          <div className="flex-1">
            <p className="font-semibold text-rose-200">Prediction Service Notification</p>
            <p className="text-rose-300/80 mt-0.5">{error}</p>
          </div>
          <button
            onClick={() => handleRunPrediction(false)}
            className="px-3 py-1 text-xs font-mono rounded-lg bg-rose-500/20 hover:bg-rose-500/30 text-rose-200 border border-rose-500/30 transition-colors cursor-pointer"
          >
            Retry
          </button>
        </div>
      )}

      {/* Main Prediction Grid - 4 Functional Cards */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-6 mb-8">
        {/* Card 1: Latest Observed AAPL Close (Actual Historical Observation) */}
        <div className="glass-panel glass-panel-hover p-6 rounded-3xl relative overflow-hidden border-slate-800">
          <div className="flex items-center justify-between">
            <span className="text-[10px] font-mono uppercase tracking-wider text-slate-400 bg-slate-800/80 px-2 py-0.5 rounded border border-slate-700">
              HISTORICAL OBSERVATION
            </span>
            <span className="text-xs font-mono text-cyan-400">AAPL</span>
          </div>

          <div className="mt-4 flex items-baseline gap-2">
            <span className="text-4xl sm:text-5xl font-black text-white font-mono">
              ${prediction ? prediction.current_price.toFixed(2) : "---.--"}
            </span>
            <span className="text-xs font-mono text-slate-500">USD</span>
          </div>

          <div className="mt-4 pt-3 border-t border-white/5 space-y-1 text-[11px] font-mono text-slate-400">
            <div className="flex items-center justify-between">
              <span>Market As-Of Date:</span>
              <span className="text-slate-200">{prediction ? prediction.as_of_date : "Latest Close"}</span>
            </div>
            <div className="flex items-center justify-between">
              <span>Feed Freshness:</span>
              <span className="text-emerald-400">
                {prediction?.is_cached ? "In-Memory Cache (300s TTL)" : "Live Feed Synced"}
              </span>
            </div>
          </div>
        </div>

        {/* Card 2: Estimated Next-Session Close (Model Forecast) */}
        <div className="glass-panel glass-panel-hover p-6 rounded-3xl relative overflow-hidden border-emerald-500/40 ring-1 ring-emerald-500/20 bg-emerald-950/[0.12]">
          <div className="absolute -top-12 -right-12 w-28 h-28 bg-emerald-500/10 rounded-full blur-2xl" />
          <div className="flex items-center justify-between">
            <span className="text-[10px] font-mono uppercase tracking-wider text-emerald-300 bg-emerald-500/20 px-2.5 py-0.5 rounded-full border border-emerald-500/30 flex items-center gap-1">
              <Sparkles className="w-3 h-3 text-emerald-300" />
              MODEL FORECAST (ESTIMATE)
            </span>
            <span className="text-[10px] font-mono text-emerald-400">NEXT CLOSE</span>
          </div>

          <div className="mt-4 flex items-baseline gap-2">
            <span className="text-4xl sm:text-5xl font-black text-emerald-400 font-mono">
              ${prediction ? prediction.predicted_next_price.toFixed(2) : "---.--"}
            </span>
            <span className="text-xs font-mono text-emerald-300 font-semibold">EST</span>
          </div>

          <div className="mt-4 pt-3 border-t border-emerald-500/20 space-y-1 text-[11px] font-mono text-slate-300">
            <div className="flex items-center justify-between">
              <span>Target Trading Session:</span>
              <span className="text-emerald-300 font-bold">
                {prediction ? prediction.target_date : "Pending"}
              </span>
            </div>
            <div className="flex items-center justify-between text-slate-400">
              <span>Formula:</span>
              <span>Price × (1 + Return)</span>
            </div>
          </div>
        </div>

        {/* Card 3: Estimated Next-Session Percentage Return */}
        <div className="glass-panel glass-panel-hover p-6 rounded-3xl relative overflow-hidden">
          <div className="flex items-center justify-between">
            <span className="text-[10px] font-mono uppercase tracking-wider text-slate-400 bg-slate-800/80 px-2 py-0.5 rounded border border-slate-700">
              ESTIMATED RETURN
            </span>
            <span className="text-xs font-mono text-slate-500">TARGET VALUE</span>
          </div>

          <div className="mt-4 flex items-baseline gap-2">
            <span
              className={`text-4xl sm:text-5xl font-black font-mono ${
                prediction
                  ? isUp
                    ? "text-emerald-400"
                    : "text-rose-400"
                  : "text-white"
              }`}
            >
              {prediction
                ? `${isUp ? "+" : ""}${prediction.predicted_return_percent.toFixed(2)}%`
                : "--.--%"}
            </span>
          </div>

          <div className="mt-4 pt-3 border-t border-white/5 space-y-1 text-[11px] font-mono">
            <div className="flex items-center justify-between">
              <span className="text-slate-400">Directional Bias:</span>
              {prediction ? (
                isUp ? (
                  <span className="text-emerald-400 font-bold inline-flex items-center gap-0.5">
                    <ArrowUpRight className="w-3.5 h-3.5" /> Positive Movement
                  </span>
                ) : (
                  <span className="text-rose-400 font-bold inline-flex items-center gap-0.5">
                    <ArrowDownRight className="w-3.5 h-3.5" /> Negative Movement
                  </span>
                )
              ) : (
                <span className="text-slate-500">Awaiting inference</span>
              )}
            </div>
            <div className="flex items-center justify-between text-slate-400">
              <span>Raw Return (Delta):</span>
              <span className="text-slate-300">
                {prediction ? prediction.predicted_return.toFixed(6) : "0.000000"}
              </span>
            </div>
          </div>
        </div>

        {/* Card 4: Predicted Direction & Model Health */}
        <div className="glass-panel glass-panel-hover p-6 rounded-3xl relative overflow-hidden">
          <div className="flex items-center justify-between">
            <span className="text-[10px] font-mono uppercase tracking-wider text-slate-400 bg-slate-800/80 px-2 py-0.5 rounded border border-slate-700">
              PREDICTED DIRECTION
            </span>
            <span className="text-xs font-mono text-slate-500">CLASSIFICATION</span>
          </div>

          <div className="mt-3 flex items-center gap-3">
            <div
              className={`w-12 h-12 rounded-2xl flex items-center justify-center border ${
                prediction
                  ? isUp
                    ? "bg-emerald-500/20 border-emerald-500/40 text-emerald-400"
                    : "bg-rose-500/20 border-rose-500/40 text-rose-400"
                  : "bg-slate-800 border-slate-700 text-slate-400"
              }`}
            >
              {isUp ? (
                <ArrowUpRight className="w-7 h-7" />
              ) : (
                <ArrowDownRight className="w-7 h-7" />
              )}
            </div>
            <div>
              <span className="text-3xl font-black text-white font-mono">
                {prediction ? prediction.direction : "PENDING"}
              </span>
              <p className="text-[10px] font-mono text-slate-400">For Next Trading Session</p>
            </div>
          </div>

          <div className="mt-4 pt-3 border-t border-white/5 space-y-1 text-[11px] font-mono text-slate-400">
            <div className="flex items-center justify-between">
              <span>Model Status:</span>
              <span className="text-emerald-400">
                {prediction?.model_status || "Operational"}
              </span>
            </div>
            <div className="flex items-center justify-between">
              <span>Signals Evaluated:</span>
              <span className="text-slate-200">25 Engineered Features</span>
            </div>
          </div>
        </div>
      </div>

      {/* Uncertainty Notice & Timestamp Audit Strip */}
      <div className="glass-panel p-5 rounded-2xl border border-white/10 mb-8 space-y-3">
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 text-xs">
          <div className="flex items-start sm:items-center gap-2.5 text-slate-300">
            <Info className="w-4 h-4 text-cyan-400 shrink-0 mt-0.5 sm:mt-0" />
            <span>
              <strong className="text-white">Uncertainty Notice:</strong> Prediction uncertainty is <em>not statistically calibrated</em>. In financial time-series forecasting, market noise is substantial; this model outputs an uncalibrated point estimate rather than a guaranteed interval or probability.
            </span>
          </div>
          <span className="shrink-0 text-[11px] font-mono text-slate-400">
            Confidence: <span className="text-amber-400">Uncalibrated Point Estimate</span>
          </span>
        </div>

        <div className="pt-2 border-t border-white/5 flex flex-wrap items-center justify-between gap-4 text-[11px] font-mono text-slate-400">
          <div className="flex flex-wrap items-center gap-4">
            <span>
              Market Data Timestamp:{" "}
              <strong className="text-slate-300">
                {prediction?.market_data_timestamp || (prediction ? `${prediction.as_of_date} Close` : "---")}
              </strong>
            </span>
            <span>
              Inference Generation:{" "}
              <strong className="text-slate-300">
                {prediction?.prediction_timestamp ? new Date(prediction.prediction_timestamp).toLocaleTimeString() : (lastUpdated || "---")}
              </strong>
            </span>
          </div>
          <div className="text-slate-400">
            Target Session: <span className="text-emerald-400 font-semibold">{prediction?.target_date || "Pending Next Open"}</span>
          </div>
        </div>
      </div>

      {/* Section I: Prediction Session History (Client-Side Audit Trail) */}
      <div className="glass-panel p-6 sm:p-8 rounded-3xl border border-white/10">
        <div className="flex items-center justify-between mb-4">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-xl bg-emerald-500/10 border border-emerald-500/20 text-emerald-400">
              <History className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-lg font-bold text-white tracking-tight">
                Prediction Audit History
              </h3>
              <p className="text-xs text-slate-400 font-light mt-0.5">
                Transparent session log of generated model estimates. Actual outcomes remain pending until the target session closes.
              </p>
            </div>
          </div>

          {historyLog.length > 0 && (
            <button
              onClick={clearHistory}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-mono bg-slate-900 border border-slate-800 text-slate-400 hover:text-rose-400 transition-colors cursor-pointer"
            >
              <Trash2 className="w-3.5 h-3.5" />
              <span>Clear History</span>
            </button>
          )}
        </div>

        {historyLog.length === 0 ? (
          <div className="py-8 text-center text-slate-500 font-mono text-xs">
            No historical session predictions recorded yet. Click &quot;Run Prediction&quot; to log an inference audit record.
          </div>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs font-mono">
              <thead>
                <tr className="border-b border-white/10 text-slate-400 uppercase text-[10px]">
                  <th className="py-2.5 pr-4">Generated At</th>
                  <th className="py-2.5 px-4">Input As-Of</th>
                  <th className="py-2.5 px-4">Target Session</th>
                  <th className="py-2.5 px-4">Observed Close</th>
                  <th className="py-2.5 px-4">Predicted Close</th>
                  <th className="py-2.5 px-4">Expected Return</th>
                  <th className="py-2.5 px-4">Direction</th>
                  <th className="py-2.5 pl-4">Session Outcome</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-white/5 text-slate-300">
                {historyLog.map((entry) => (
                  <tr key={entry.id} className="hover:bg-white/[0.02] transition-colors">
                    <td className="py-3 pr-4 text-slate-400">
                      {new Date(entry.predictionTimestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' })}
                    </td>
                    <td className="py-3 px-4">{entry.asOfDate}</td>
                    <td className="py-3 px-4 text-emerald-400 font-semibold">{entry.targetTradingDate}</td>
                    <td className="py-3 px-4">${entry.currentPrice.toFixed(2)}</td>
                    <td className="py-3 px-4 font-bold text-white">${entry.predictedNextPrice.toFixed(2)}</td>
                    <td className={`py-3 px-4 font-bold ${entry.direction === "UP" ? "text-emerald-400" : "text-rose-400"}`}>
                      {entry.direction === "UP" ? "+" : ""}{entry.predictedReturnPercent.toFixed(2)}%
                    </td>
                    <td className="py-3 px-4">
                      <span className={`inline-flex items-center gap-1 px-2 py-0.5 rounded text-[10px] ${
                        entry.direction === "UP"
                          ? "bg-emerald-500/10 text-emerald-300 border border-emerald-500/20"
                          : "bg-rose-500/10 text-rose-300 border border-rose-500/20"
                      }`}>
                        {entry.direction}
                      </span>
                    </td>
                    <td className="py-3 pl-4">
                      <span className="text-[10px] px-2 py-0.5 rounded bg-slate-900 border border-slate-800 text-slate-400">
                        {entry.status}
                      </span>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </section>
  );
};
