"use client";

import React, { useState, useEffect } from "react";
import { 
  Play, 
  RotateCw, 
  ArrowUpRight, 
  ArrowDownRight, 
  Calendar, 
  Cpu, 
  AlertCircle, 
  CheckCircle2, 
  ShieldAlert, 
  Sparkles 
} from "lucide-react";
import { PredictionResponse } from "@/types/api";
import { fetchPrediction } from "@/lib/api";

interface DashboardProps {
  initialPrediction: PredictionResponse | null;
  onPredictionUpdated?: (pred: PredictionResponse) => void;
}

export const LivePredictionDashboard: React.FC<DashboardProps> = ({
  initialPrediction,
  onPredictionUpdated
}) => {
  const [prediction, setPrediction] = useState<PredictionResponse | null>(initialPrediction);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [lastUpdated, setLastUpdated] = useState<string | null>(null);

  useEffect(() => {
    if (initialPrediction) {
      setPrediction(initialPrediction);
      setLastUpdated(new Date().toLocaleTimeString());
    }
  }, [initialPrediction]);

  const handleRunPrediction = async (force: boolean = true) => {
    setLoading(true);
    setError(null);
    try {
      const result = await fetchPrediction(force);
      setPrediction(result);
      setLastUpdated(new Date().toLocaleTimeString());
      if (onPredictionUpdated) {
        onPredictionUpdated(result);
      }
    } catch (err: unknown) {
      console.error("Prediction error:", err);
      setError(err instanceof Error ? err.message : "Market data temporarily unavailable. Please retry.");
    } finally {
      setLoading(false);
    }
  };

  const isUp = prediction?.direction === "UP";

  return (
    <section id="prediction-dashboard" className="py-24 px-4 sm:px-6 lg:px-8 max-w-7xl mx-auto">
      {/* Section Header */}
      <div className="flex flex-col md:flex-row md:items-end justify-between mb-10 gap-4">
        <div>
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-emerald-500/10 border border-emerald-500/20 text-emerald-400 text-xs font-mono mb-3">
            <Cpu className="w-3.5 h-3.5" />
            <span>LIVE INFERENCE ENGINE</span>
          </div>
          <h2 className="text-3xl sm:text-5xl font-extrabold text-white tracking-tight">
            Prediction Dashboard
          </h2>
          <p className="text-slate-400 text-sm sm:text-base mt-2 max-w-2xl font-light">
            Real-time inference generated by the trained XGBoost model using fresh yfinance market feeds and 25 engineered technical signals.
          </p>
        </div>

        {/* Action Button */}
        <div className="flex items-center gap-3">
          <button
            onClick={() => handleRunPrediction(true)}
            disabled={loading}
            className={`flex items-center gap-2 px-6 py-3 rounded-xl font-bold text-sm tracking-wide uppercase transition-all shadow-xl cursor-pointer ${
              loading
                ? "bg-slate-800 text-slate-400 cursor-not-allowed border border-slate-700"
                : "bg-gradient-to-r from-emerald-500 to-teal-400 hover:from-emerald-400 hover:to-teal-300 text-slate-950 shadow-emerald-500/25 active:scale-95"
            }`}
          >
            {loading ? (
              <>
                <RotateCw className="w-4 h-4 animate-spin text-emerald-400" />
                <span>Running Model...</span>
              </>
            ) : (
              <>
                <Play className="w-4 h-4 fill-slate-950" />
                <span>Run Prediction</span>
              </>
            )}
          </button>
        </div>
      </div>

      {/* Error Banner */}
      {error && (
        <div className="mb-8 p-4 rounded-2xl bg-rose-500/10 border border-rose-500/20 flex items-start gap-3 text-rose-300 text-sm">
          <AlertCircle className="w-5 h-5 text-rose-400 shrink-0 mt-0.5" />
          <div className="flex-1">
            <p className="font-semibold text-rose-200">Prediction Service Notice</p>
            <p className="text-rose-300/80 mt-0.5">{error}</p>
          </div>
          <button
            onClick={() => handleRunPrediction(false)}
            className="px-3 py-1 text-xs font-mono rounded-lg bg-rose-500/20 hover:bg-rose-500/30 text-rose-200 border border-rose-500/30 transition-colors"
          >
            Retry
          </button>
        </div>
      )}

      {/* Main Prediction Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-6 mb-8">
        {/* Card 1: Current Apple Price */}
        <div className="glass-panel glass-panel-hover p-6 rounded-3xl relative overflow-hidden">
          <div className="absolute top-0 right-0 p-6 pointer-events-none opacity-10">
            <span className="text-6xl font-bold font-mono text-white">AAPL</span>
          </div>
          <span className="text-xs font-mono uppercase tracking-wider text-slate-400">
            CURRENT AAPL PRICE
          </span>
          <div className="mt-3 flex items-baseline gap-2">
            <span className="text-4xl sm:text-5xl font-black text-white font-mono">
              ${prediction ? prediction.current_price.toFixed(2) : "---.--"}
            </span>
            <span className="text-xs font-mono text-slate-400">USD</span>
          </div>
          <div className="mt-4 flex items-center gap-1.5 text-xs text-slate-400">
            <Calendar className="w-3.5 h-3.5 text-slate-400" />
            <span>As of: {prediction ? prediction.as_of_date : "Latest market close"}</span>
          </div>
        </div>

        {/* Card 2: Predicted Next Close */}
        <div className="glass-panel glass-panel-hover p-6 rounded-3xl relative overflow-hidden border-emerald-500/30">
          <div className="absolute -top-12 -right-12 w-28 h-28 bg-emerald-500/10 rounded-full blur-2xl" />
          <span className="text-xs font-mono uppercase tracking-wider text-emerald-400 flex items-center gap-1.5">
            <Sparkles className="w-3.5 h-3.5 text-emerald-400" />
            PREDICTED NEXT CLOSE
          </span>
          <div className="mt-3 flex items-baseline gap-2">
            <span className="text-4xl sm:text-5xl font-black text-emerald-400 font-mono">
              ${prediction ? prediction.predicted_next_price.toFixed(2) : "---.--"}
            </span>
            <span className="text-xs font-mono text-emerald-300">EST</span>
          </div>
          <div className="mt-4 text-xs text-slate-400 font-mono">
            Model: <span className="text-slate-200">XGBoost Regressor</span>
          </div>
        </div>

        {/* Card 3: Expected Return */}
        <div className="glass-panel glass-panel-hover p-6 rounded-3xl relative overflow-hidden">
          <span className="text-xs font-mono uppercase tracking-wider text-slate-400">
            EXPECTED RETURN
          </span>
          <div className="mt-3 flex items-baseline gap-2">
            <span
              className={`text-4xl sm:text-5xl font-black font-mono ${
                prediction
                  ? isUp
                    ? "text-emerald-400"
                    : "text-rose-400"
                  : "text-white"
              }`}
            >
              {prediction
                ? `${isUp ? "+" : ""}${prediction.predicted_return_percent.toFixed(2)}%`
                : "--.--%"}
            </span>
          </div>
          <div className="mt-4 flex items-center gap-1 text-xs">
            {prediction ? (
              isUp ? (
                <span className="inline-flex items-center gap-1 text-emerald-400 font-mono">
                  <ArrowUpRight className="w-4 h-4" /> Positive Bias
                </span>
              ) : (
                <span className="inline-flex items-center gap-1 text-rose-400 font-mono">
                  <ArrowDownRight className="w-4 h-4" /> Negative Bias
                </span>
              )
            ) : (
              <span className="text-slate-400">Awaiting inference</span>
            )}
          </div>
        </div>

        {/* Card 4: Directional Forecast */}
        <div className="glass-panel glass-panel-hover p-6 rounded-3xl relative overflow-hidden">
          <span className="text-xs font-mono uppercase tracking-wider text-slate-400">
            DIRECTIONAL FORECAST
          </span>
          <div className="mt-3 flex items-center gap-3">
            <div
              className={`w-12 h-12 rounded-2xl flex items-center justify-center border ${
                prediction
                  ? isUp
                    ? "bg-emerald-500/20 border-emerald-500/40 text-emerald-400"
                    : "bg-rose-500/20 border-rose-500/40 text-rose-400"
                  : "bg-slate-800 border-slate-700 text-slate-400"
              }`}
            >
              {isUp ? (
                <ArrowUpRight className="w-7 h-7" />
              ) : (
                <ArrowDownRight className="w-7 h-7" />
              )}
            </div>
            <div>
              <span className="text-3xl font-black text-white font-mono">
                {prediction ? prediction.direction : "PENDING"}
              </span>
              <p className="text-[11px] font-mono text-slate-400">Next Trading Session</p>
            </div>
          </div>
          <div className="mt-4 flex items-center gap-2 text-[11px] font-mono text-slate-400">
            <span className="w-2 h-2 rounded-full bg-emerald-400 animate-pulse" />
            <span>25 Features Evaluated</span>
          </div>
        </div>
      </div>

      {/* Honest Transparency Footer Banner */}
      <div className="glass-panel p-4 sm:p-5 rounded-2xl border border-white/5 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 text-xs text-slate-400">
        <div className="flex items-center gap-2.5">
          <ShieldAlert className="w-4 h-4 text-amber-400 shrink-0" />
          <span>
            <strong className="text-slate-200">ML Estimation Notice:</strong> Machine-learning prediction models capture statistical patterns in historical market data. Next-day equity returns have high intrinsic noise; this output is for educational demonstration only.
          </span>
        </div>
        {lastUpdated && (
          <span className="font-mono text-slate-400 shrink-0">
            Synced: {lastUpdated}
          </span>
        )}
      </div>
    </section>
  );
};
